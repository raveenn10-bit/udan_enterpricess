class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('udan_lang') || 'en';
    if (!TRANSLATIONS[this.currentLang]) {
      this.currentLang = 'en';
    }
    this.init();
  }

  init() {
    document.addEventListener('DOMContentLoaded', () => {
      this.applyTranslations();
      this.setupLanguageSwitchers();
    });
    // In case DOM is already loaded
    if (document.readyState === 'interactive' || document.readyState === 'complete') {
      this.applyTranslations();
      this.setupLanguageSwitchers();
    }
  }

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('udan_lang', lang);
    document.documentElement.lang = lang;
    this.applyTranslations();
    this.updateActiveSwitcherState();
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  getLanguage() {
    return this.currentLang;
  }

  t(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  }

  applyTranslations() {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    
    // Replace text of elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.getAttribute('data-i18n-html') === 'true' || dict[key].includes('<')) {
          el.innerHTML = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Replace placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    // Replace titles or aria-labels
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.title = dict[key];
      }
    });
  }

  setupLanguageSwitchers() {
    // Look for language switcher containers or buttons
    document.querySelectorAll('.lang-switcher select, select[data-lang-select]').forEach(select => {
      select.value = this.currentLang;
      select.onchange = (e) => this.setLanguage(e.target.value);
    });

    document.querySelectorAll('[data-set-lang]').forEach(btn => {
      btn.onclick = (e) => {
        e.preventDefault();
        const lang = btn.getAttribute('data-set-lang');
        this.setLanguage(lang);
      };
    });

    this.updateActiveSwitcherState();
  }

  updateActiveSwitcherState() {
    document.querySelectorAll('.lang-switcher select, select[data-lang-select]').forEach(select => {
      select.value = this.currentLang;
    });

    document.querySelectorAll('[data-set-lang]').forEach(btn => {
      if (btn.getAttribute('data-set-lang') === this.currentLang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });
  }
}

// Global instance
window.i18n = new I18nEngine();
